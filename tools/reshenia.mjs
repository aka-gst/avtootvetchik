/*
 * СКОЛЬКИМИ СПОСОБАМИ ПРОХОДИТСЯ КОМНАТА
 * =========================================================
 * Первое из трёх измерений приёмки: **решения существуют**. Оно не
 * заменяет живых людей — те проверяют, что решения ФИНДЯТ, — но отвечает
 * на предыдущий вопрос, и отвечает дёшево.
 *
 * Игрок здесь нарочно случайный, а не умный. Умный бот всегда играет
 * одинаково и даёт один след: он проверит, что комната проходима, и
 * ничего не скажет о числе решений. Ощущение «можно всё» рождается из
 * попадания наугад — значит и мерить надо тем, кто тычет наугад.
 *
 * Считаются не прохождения, а различные наборы сработавших правил:
 * канонический след из trace.js. Два прохождения с одним набором — одно
 * решение, как бы по-разному их ни играли.
 *
 * Запуск: node tools/reshenia.mjs [сколько прогонов]
 */

import { CAMPAIGN } from '../src/levels.js';
import { createWorld, update, TILE_SIZE, hasShot } from '../src/world.js';
import { TILE, weakTo } from '../src/level.js';
import { ELEMENT_ORDER } from '../src/magic.js';
import { createTrace, traceEvent, traceKey } from '../src/trace.js';

const DT = 1 / 60;
const idle = { moveX: 0, moveY: 0, aimAngle: null, attack: false, charge: null };

function seeded(seed) {
  let value = seed >>> 0;
  return () => {
    value = (value * 1664525 + 1013904223) >>> 0;
    return value / 4294967296;
  };
}

/*
 * Всё, во что вообще можно целиться: живые и всё ломаемое — **предметами,
 * а не клетками**.
 *
 * Это не мелочь, а третий за вечер случай, когда измеритель считал не то,
 * что назывался считать. Копна занимает девять клеток, щиток одну, бочка
 * одну; выбирая случайную клетку, модель выбирала копну девять раз из
 * пятнадцати — и я чуть не объявил это перевесом копны в устройстве
 * уровня. Человек видит один стог, а не девять стогов.
 *
 * Соседние клетки одного вида собираются в один предмет с общим центром,
 * ровно как при приёмке графики: геометрия без имён.
 */
function цели(world) {
  const out = world.enemies.filter((enemy) => enemy.alive)
    .map((enemy) => ({ x: enemy.x, y: enemy.y, вид: null }));

  const занято = new Set();

  for (let i = 0; i < world.tiles.length; i += 1) {
    if (занято.has(i) || !weakTo(world.tiles[i])) continue;

    const вид = world.tiles[i];
    const куски = [i];
    занято.add(i);

    for (let k = 0; k < куски.length; k += 1) {
      const at = куски[k];
      const tx = at % world.w;
      const ty = (at / world.w) | 0;
      for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
        const nx = tx + dx;
        const ny = ty + dy;
        if (nx < 0 || ny < 0 || nx >= world.w || ny >= world.h) continue;
        const рядом = ny * world.w + nx;
        if (занято.has(рядом) || world.tiles[рядом] !== вид) continue;
        занято.add(рядом);
        куски.push(рядом);
      }
    }

    let sx = 0;
    let sy = 0;
    for (const at of куски) {
      sx += ((at % world.w) + 0.5) * TILE_SIZE;
      sy += (((at / world.w) | 0) + 0.5) * TILE_SIZE;
    }

    out.push({ x: sx / куски.length, y: sy / куски.length, вид });
  }

  return out;
}

/*
 * Откуда начинать. По умолчанию — со входа на этаж, но у обучалки перед
 * комнатой стоит коридор из двух запертых створок, и случайный игрок
 * почти всегда застревает в нём: шестьдесят один прогон из ста двадцати
 * не дошёл вообще ни до одного правила.
 *
 * Тогда измерение меряет вход, а не комнату, а замысел спрашивает именно
 * про комнату — «одна комната с пятью решениями». Поэтому начальную
 * клетку можно задать: node tools/reshenia.mjs 120 10,12
 */
function выходНа(world) {
  for (let i = 0; i < world.tiles.length; i += 1) {
    if (world.tiles[i] !== TILE.EXIT) continue;
    return { x: ((i % world.w) + 0.5) * TILE_SIZE, y: (((i / world.w) | 0) + 0.5) * TILE_SIZE };
  }
  return null;
}

function прогон(floor, seed, откуда, секунд = 60, толково = true, контроль = false) {
  const rnd = seeded(seed);
  const было = Math.random;
  Math.random = rnd;

  try {
    const world = createWorld(floor);

    /*
     * ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ
     * -------------------------------------------------------
     * Комната, где ответ известен заранее: ни одного ломаемого предмета и
     * ни одного живого. Правил сработать не может, и измеритель обязан
     * показать ноль.
     *
     * Нужен он не для порядка. Модель игрока я за час поправил трижды, и
     * каждая правка улучшала числа; заморозить её мало — замороженную
     * тоже надо чем-то оправдать, иначе мы просто закрепили удобную. Если
     * на пустой комнате она что-то насчитает, значит она меряет себя,
     * только тише.
     */
    if (контроль) {
      for (let i = 0; i < world.tiles.length; i += 1) {
        if (weakTo(world.tiles[i])) world.tiles[i] = TILE.FLOOR;
      }
      for (const enemy of world.enemies) enemy.alive = false;
      world.total = 0;
    }

    if (откуда) {
      world.player.x = (откуда[0] + 0.5) * TILE_SIZE;
      world.player.y = (откуда[1] + 0.5) * TILE_SIZE;
    }
    const trace = createTrace();
    let набор = [];
    /* Времена вырубаний внутри одного прогона. Срок сна надо мерить не
       «хватает ли уйти» — уйти хватает всегда, до выхода две секунды, —
       а «успеваешь ли положить остальных, пока первый лежит». */
    const когда = [];

    for (let f = 0; f < секунд / DT && world.player.alive; f += 1) {
      const цель = цели(world);
      const intent = { ...idle };

      /* Набираем случайную стихию, пока очередь не полна, потом бьём в
         случайную цель. Ни тактики, ни памяти — только тыканье. */
      if (world.player.chargeLeft <= 0) {
        if (набор.length < 3 && rnd() < 0.06) {
          const id = world.elements[Math.floor(rnd() * world.elements.length)];
          intent.charge = id;
          набор.push(id);
        } else if (набор.length && цель.length && rnd() < 0.08) {
          /*
           * Случайным должен быть ВЫБОР, а не меткость. Первая версия
           * била в случайную цель не глядя, и половина выстрелов уходила
           * в стену: измерение получалось про умение прицелиться, а не
           * про число решений, и обвиняло уровень в том, чего он не
           * делал. Стреляем только туда, куда долетит.
           */
          /*
           * Луч ведётся до ЛИЦЕВОЙ стороны цели, а не до её середины.
           * Иначе предмет загораживает сам себя, и «толковый» игрок не
           * мог целиться ни во что, что держит выстрел: ни в щиток, ни в
           * бочку, ни в кристалл. Оставалась одна солома — сквозь неё
           * стреляют насквозь, — и она честно набирала свои проценты.
           *
           * Это четвёртый за вечер случай, когда измеритель мерил не то,
           * что назывался мерить, и третий раз подряд — из-за луча до
           * середины клетки. Ту же ошибку я уже чинил в прицеле самой
           * игры, и она вернулась в инструменте.
           */
          /*
           * И второе, чему толковый игрок обязан быть обучен: не бить по
           * взрывоопасному в упор. Бочка разливает воду, кристалл бьёт
           * разрядом, вода проводит — цепь возвращается к стрелявшему.
           * Владелец прямо сказал, что тактика тут не только «как всех
           * убить», но и «как не пострадать самому»; значит уклонение от
           * собственной цепи — часть умения, а не поблажка модели.
           */
          const видимые = толково
            ? цель.filter((t) => {
              if (t.вид === TILE.BARREL || t.вид === TILE.CRYSTAL) {
                if (Math.hypot(t.x - world.player.x, t.y - world.player.y)
                  < TILE_SIZE * 2.5) return false;
              }
              const dx = t.x - world.player.x;
              const dy = t.y - world.player.y;
              const dist = Math.hypot(dx, dy) || 1;
              const назад = Math.min(dist - 1, TILE_SIZE * 0.7);
              return hasShot(world, world.player.x, world.player.y,
                t.x - (dx / dist) * назад, t.y - (dy / dist) * назад);
            })
            : цель;
          if (видимые.length) {
            const t = видимые[Math.floor(rnd() * видимые.length)];
            intent.aimAngle = Math.atan2(t.y - world.player.y, t.x - world.player.x);
            intent.attack = true;
            набор = [];
          }
        }
      }

      /*
       * И бродим — но к ближайшей цели, а не куда попало. Полное
       * блуждание тоже мерило не то: случайный игрок за минуту не
       * доходил до второй комнаты, и половина прогонов заканчивалась ни
       * на чём. Куда идти — не выбор игрока, это дорога; выбор в том,
       * что он там сделает.
       */
      if (толково && rnd() < 0.05 && цель.length) {
        const t = цель[Math.floor(rnd() * цель.length)];
        const a = Math.atan2(t.y - world.player.y, t.x - world.player.x)
          + (rnd() - 0.5) * 1.4;
        intent.moveX = Math.cos(a);
        intent.moveY = Math.sin(a);
      } else if (rnd() < 0.02) {
        /*
         * Иногда — к выходу. Живой игрок хочет пройти комнату, а не
         * гулять по ней: без этого нижняя половина уровня не посещалась
         * вовсе, и щиток с силовой стеной не встретились ни разу за сто
         * прогонов. Не цель, а склонность: тянет туда, но не ведёт.
         */
        const выход = выходНа(world);
        const a = выход
          ? Math.atan2(выход.y - world.player.y, выход.x - world.player.x) + (rnd() - 0.5) * 1.2
          : rnd() * Math.PI * 2;
        intent.moveX = Math.cos(a);
        intent.moveY = Math.sin(a);
      } else if (rnd() < 0.03) {
        const a = rnd() * Math.PI * 2;
        intent.moveX = Math.cos(a);
        intent.moveY = Math.sin(a);
      }

      update(world, DT, intent);
      for (const event of world.events) {
        traceEvent(trace, event);
        if (event.type === 'sleep') { вырублено += 1; когда.push(f * DT); }
        if (event.type === 'wake') встало += 1;
        if (event.type === 'kill' && event.execution) добито += 1;
      }
    }

    /*
     * Судьба вырубленных — отдельное число, и ради него всё затевалось.
     * Срок сна годится только если В ХОДУ ОБА ИСХОДА: и «ушёл, пока тот
     * лежал», и «не успел, тот встал». Если просыпаются все, вырубать
     * незачем; если никто — вырубание это бесплатное убийство, и убивать
     * незачем. Считаем поэтому не сон, а чем он кончился.
     */
    for (const enemy of world.enemies) {
      if (enemy.alive && enemy.downed > 0) лежит += 1;
    }

    if (когда.length >= 2) размахи.push(когда[когда.length - 1] - когда[0]);

    return { след: traceKey(trace), правил: trace.rules.size, убито: world.kills, жив: world.player.alive };
  } finally {
    Math.random = было;
  }
}

const сколько = Number(process.argv[2]) || 60;
const откуда = process.argv[3] && process.argv[3].includes(',')
  ? process.argv[3].split(',').map(Number) : null;
const секунд = Number(process.argv[4] || (откуда ? 0 : process.argv[3])) || 60;

/*
 * Две модели игрока, и разница между ними — половина смысла инструмента.
 *
 * «Толковый» целится только туда, куда долетит, и бродит в сторону целей.
 * «Наугад» бьёт не глядя и ходит куда попало.
 *
 * Числа у них расходятся вдвое и втрое, и наивный вывод «чем больше
 * решений, тем лучше» тут ломается: наугад даёт БОЛЬШЕ различных следов,
 * потому что чаще попадает случайно. Это не богатство комнаты, это шум
 * модели. Живой человек ближе к толковому, и мерить надо им, а второй
 * держать как границу снизу.
 *
 * Переключается переменной RANDOM_PLAY=1 — латиницей, потому что
 * оболочка не всякое имя переменной принимает.
 */
const толково = process.env.RANDOM_PLAY !== '1';
const контроль = process.env.CONTROL === '1';
const floor = CAMPAIGN[0];

const следы = new Map();
let живых = 0;
let вырублено = 0;
let добито = 0;
let лежит = 0;
let встало = 0;
const размахи = [];

for (let i = 0; i < сколько; i += 1) {
  const r = прогон(floor, 20260830 + i * 7919, откуда, секунд, толково, контроль);
  if (r.жив) живых += 1;
  if (!r.правил) continue;
  следы.set(r.след, (следы.get(r.след) || 0) + 1);
}

const всего = [...следы.values()].reduce((a, b) => a + b, 0);
const частый = Math.max(0, ...следы.values());

console.log(`этаж: ${floor.title}${откуда ? `, старт с клетки ${откуда.join(',')}` : ''}`
  + `, по ${секунд} секунд, игрок ${толково ? 'толковый' : 'наугад'}`
  + (контроль ? ', ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: пустая комната' : ''));
console.log(`прогонов: ${сколько}, из них с хоть одним правилом: ${всего}, выжил в ${живых}`);
console.log(`вырублено за все прогоны: ${вырублено} · из них добито ${добито}, `
  + `осталось лежать к концу ${лежит}, встало само ${встало}`);
if (размахи.length) {
  размахи.sort((a, b) => a - b);
  const медиана = размахи[размахи.length >> 1];
  console.log(`от первого вырубания до последнего: медиана ${медиана.toFixed(1)} с `
    + `(от ${размахи[0].toFixed(1)} до ${размахи[размахи.length - 1].toFixed(1)}), `
    + `прогонов с двумя и более: ${размахи.length}`);
}
console.log(`различных решений: ${следы.size}`);
console.log(`доля самого частого: ${всего ? Math.round(частый / всего * 100) : 0}%`);
console.log('');

for (const [след, раз] of [...следы.entries()].sort((a, b) => b[1] - a[1]).slice(0, 12)) {
  console.log(String(раз).padStart(3), след);
}

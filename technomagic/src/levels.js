/*
 * ТЕХНОМАГИЯ — встроенные этажи.
 *
 * Каждый уровень — картинка. Символы: # ограда, . земля, , газон, = скамья,
 * | стекло, + створка, X выход, @ вход игрока, t громила, s стрелок,
 * o бочка с водой, O валун, * кристалл, h стог соломы,
 * f/w/v/e/l — носители щитов огня, воды, ветра, земли и молнии.
 *
 * Внутри игра работает с теми же уровнями, что приходят кодом: картинка
 * превращается в структуру, структура кодируется. Своих привилегий у
 * встроенных этажей нет — если формат сломается, они сломаются первыми.
 *
 * Стихии этаж выдаёт сам, и это поле формата, а не свойство сохранённого
 * игрока. Причина простая: этаж уезжает по ссылке чужому человеку, и он
 * обязан открыться у него так же, как у автора. Прогресс, живущий в
 * браузере, сделал бы один и тот же код разной игрой у двух людей.
 *
 * Порядок открытия — порядок обучения, и начинается он не с воды.
 * Обучалка даёт огонь и молнию, а воду выдаёт комната: бочка, вскрытая
 * огнём, разливает лужу под ногами у врага, и разряд в эту лужу забирает
 * троих разом. Так первое, что игрок узнаёт про игру, — что стихии
 * работают друг через друга, а не по очереди.
 *
 * Дальше вода приходит в руки, потом ветер с дальностью и стужей, потом
 * земля с тяжестью, грязью и лавой.
 */


/*
 * СЧЁТЧИК СОБЫТИЙ
 * =========================================================
 * Просмотры страницы считаются сами, и этого мало: игра — не статья, её
 * не «прочитывают». Уйти можно с четырёх разных мест, и они означают
 * совершенно разное: со стартового экрана — не заинтересовала; из первого
 * боя — не понял управление; после третьей смерти — слишком сложно;
 * после зачистки — прошёл и доволен. Без этих четырёх точек любая правка
 * по игре делается вслепую.
 *
 * Обёртка нужна ровно за тем, чтобы игра ничего не знала о счётчике.
 * Счётчика может не быть вовсе: на localhost его нет, у части людей он
 * вырезан расширением, и загрузка отложена атрибутом defer — то есть в
 * первые мгновения его нет даже там, где он будет. Ни один из этих
 * случаев не должен уронить кадр, поэтому здесь всё молча глохнет.
 *
 * В события не уходит ничего про человека — только этаж и цифры самой
 * игры. Ни кода уровня, ни ссылки-вызова, ни имени: код уровня несёт в
 * себе целиком чужую постройку, а имя в вызове — то, что игрок написал
 * про себя, и ни тому, ни другому в статистике не место.
 */
export function pulse(name, data) {
  try {
    const meter = window.umami;
    if (!meter || typeof meter.track !== 'function') return;
    meter.track(name, data || {});
  } catch (error) {
    /* Счётчик не имеет права мешать игре. */
  }
}

/*
 * СЛЕД РЕШЕНИЯ
 * =========================================================
 * Комната считается получившейся не по тому, проходится ли она, а по
 * тому, сколькими разными способами её прошли. Значит с прохождения
 * должно уходить не «пройдено», а то, ЧЕМ прошли: набор сработавших
 * правил.
 *
 * Считать надо решения, а не нажатия. Иначе каждое прохождение окажется
 * неповторимым просто потому, что игрок жал кнопки в другом темпе, и
 * счётчик покажет пять решений там, где оно одно.
 *
 * Отсюда каноническая форма: **множество правил без порядка и без
 * количеств**. Два прохождения с одним набором — одно решение, как бы
 * по-разному их ни играли. Приём тот же, что при приёмке графики:
 * геометрия без имён — два предмета с одной формой это один предмет.
 *
 * В след не уходит ничего про человека: ни кодов уровней, ни имён, ни
 * времени нажатий. Только названия правил, и они одинаковы у всех.
 */

/* Правило узнаётся по событию. Ключ — что случилось в мире, значение —
   короткое имя, под которым это ляжет в статистику. */
const BY_EVENT = {
  barrel: 'bochka',        /* вскрыл бочку */
  hay: 'soloma',           /* поджёг солому */
  crystal: 'kristall',     /* разрядил кристалл */
  boulder: 'valun',        /* раздробил валун */
  chain: 'cep',            /* пустил разряд по воде */
  fling: 'telo',           /* сбил одного другим */
  backfire: 'sam',         /* задел себя вспышкой */
  'shocked-self': 'sam',   /* и своей же лужей */
  knock: 'sbil',           /* сбил с ног */
};

export function createTrace() {
  return { rules: new Set(), casts: 0 };
}

export function traceEvent(trace, event) {
  const named = BY_EVENT[event.type];
  if (named) trace.rules.add(named);

  if (event.type === 'daemon') {
    trace.casts += 1;

    /* Состав против одиночной стихии — это разные способы, и разница
       между ними и есть половина игры. */
    trace.rules.add(event.elements.length >= 2 ? 'sostav' : 'iskra');

    /* Форма записывается своим именем: луч и вспышка решают комнату
       по-разному, и складывать их в «выстрелил» нельзя. */
    if (event.form) trace.rules.add(`forma-${event.form}`);

    /* Именное заклинание — отдельное правило: его ещё надо найти. */
    if (event.signature) trace.rules.add(`imya-${event.signature}`);
  }

  if (event.type === 'kill' && event.execution) trace.rules.add('dobil');
  if (event.type === 'engaged') trace.rules.add('shum');
}

/*
 * Каноническая форма следа. Сортировка обязательна: одно и то же решение,
 * сыгранное в другом порядке, обязано дать ту же строку, иначе счёт
 * различных решений превращается в счёт прохождений.
 */
export function traceKey(trace) {
  return [...trace.rules].sort().join('+');
}
